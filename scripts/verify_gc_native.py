"""Local metadata/hash verification of native GC prototypes; no emulation."""
import argparse,json,hashlib,struct,sys,subprocess
from pathlib import Path
from audit_sd import ROOT,PRIVATE,sha256
sys.path.insert(0,str(ROOT))
from kwce.gc_native import patch_gc_native
from kwce.gc_icons import patch_gc_icons
from kwce.gc_header import patch_gc_header
from launch_dolphin import validate_native_runtime,validate,user_path

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--skip-unit-tests',action='store_true',help='caller already ran the complete unit suite')
    args=parser.parse_args()
    result=dict(passed=False)
    report=PRIVATE/'gc-native-verification.json';report.write_text(json.dumps(result))
    if 'dolphin.exe' in subprocess.run(['tasklist','/FI','IMAGENAME eq Dolphin.exe','/FO','CSV','/NH'],capture_output=True,text=True).stdout.lower():raise SystemExit('Close Dolphin before verifying stable on-disk profiles')
    original=(ROOT/'workspace/console-baseline/menu-original-43K.dol').read_bytes()
    first=(ROOT/'workspace/experiments/gc-restoration-v1/menu-resource.app').read_bytes()
    versions=[]
    for rev in [2,3,4,5,6]:
        out=ROOT/f'workspace/experiments/gc-native-v{rev}';meta=json.loads((out/'build-manifest.json').read_text(encoding='utf-8'))
        dol,detail=patch_gc_native(original,japanese_cards=rev>=3,japanese_comments=rev>=5)
        if (out/'menu-gc-native.dol').read_bytes()!=dol or hashlib.sha256(dol).hexdigest()!=meta['patched_dol_sha256']:raise ValueError('DOL output differs from reproducible build')
        profile=f'gc-native-v{rev}-user'
        pending_task_scrub=False
        try:user=validate(profile)
        except SystemExit as error:
            # Preserved inactive profiles may contain skip bits regenerated by
            # a later user session. Validate all preceding auth/locale guards;
            # never change preserved files or bypass this check for execution.
            if rev!=5 or str(error)!='A scheduled task must be scrubbed before launch':raise
            user=user_path(profile)
            pending_task_scrub=True
        content=user/'Wii/title/00000001/00000002/content'
        tmd=(content/'title.tmd').read_bytes();count=int.from_bytes(tmd[0x1de:0x1e0],'big')
        for i in range(count):
            at=0x1e4+36*i;cid,index,kind,size=struct.unpack_from('>IHHQ',tmd,at)
            if index not in [1,6]:continue
            payload=(content/f'{cid:08x}.app').read_bytes()
            if size!=len(payload) or tmd[at+16:at+36]!=hashlib.sha1(payload).digest():raise ValueError('TMD metadata mismatch')
            resource=patch_gc_icons(first)[0] if rev>=4 else first
            if rev>=6:resource=patch_gc_header(resource)[0]
            expected=dol if index==6 else resource
            if payload!=expected:raise ValueError('Installed experimental content differs')
        versions.append(dict(revision=rev,instructions=detail['instructions_changed'],content_TMD_hashes=True,preserved_profile_pending_task_scrub=pending_task_scrub))
    # Current runtime must use the locked derivative and current helper.
    # Earlier profiles are preserved; obsolete probe builds fail closed.
    validate_native_runtime('gc-native-v5-user')
    validate_native_runtime('gc-native-v6-user')
    refs=json.loads((ROOT/'configs/gc-native-references.lock.json').read_text())
    for row in refs['files']:
        if sha256(ROOT/'external/other-tools/dolphin-reference'/row['path'])!=row['sha256']:raise ValueError('Public source reference mismatch')
    if not args.skip_unit_tests:
        subprocess.run([sys.executable,'-m','unittest','discover','-s','tests'],cwd=ROOT,check=True)
    subprocess.run([sys.executable,'scripts/test_launcher_guards.py'],cwd=ROOT,check=True)
    subprocess.run([sys.executable,'-m','kwce.build','--verify'],cwd=ROOT,check=True)
    subprocess.run([sys.executable,'scripts/finalize_import.py','--check'],cwd=ROOT,check=True)
    observations={}
    for rev in [3,4]:observations[str(rev)]=json.loads((PRIVATE/f'gc-native-v{rev}-observations.json').read_text())
    # On-disk reproducibility cannot establish emulated game execution. Keep
    # the separately recorded UI observations distinct from this hash check.
    for rev in [5,6]:
        observation=PRIVATE/f'gc-native-v{rev}-observations.json'
        if observation.exists():observations[str(rev)]=json.loads(observation.read_text(encoding='utf-8'))
    disc_refs=json.loads((ROOT/'configs/gc-disc-references.lock.json').read_text())
    for row in disc_refs['files']:
        local=row.get('local',Path(row['path']).name)
        if sha256(ROOT/'external/other-tools/dolphin-reference'/local)!=row['sha256']:raise ValueError('Disc source reference mismatch')
    result=dict(passed=True,revisions=versions,public_references=len(refs['files'])+len(disc_refs['files']),observations=observations,emulation_verified_by_this_script=False,real_console_writes=False)
    report.write_text(json.dumps(result,indent=2));print(json.dumps({k:v for k,v in result.items() if k!='observations'}))

if __name__=='__main__':main()
