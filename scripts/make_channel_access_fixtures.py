def lz11_literal(data):
    out=bytearray(b'\x11'+len(data).to_bytes(3,'little'))
    for i in range(0,len(data),8):out.append(0);out.extend(data[i:i+8])
    return bytes(out)

def lz10(data):
    packed=compress_lz77(data)
    if not packed.startswith(b'LZ77\x10'):raise ValueError('Unexpected library compression wrapper')
    return packed[4:]

def lz10_literal(data):
    # A tiny synthetic catalogue does not need back-references. Literal blocks
    # also avoid the distance-one restriction of halfword LZ readers.
    out=bytearray(b'\x10'+len(data).to_bytes(3,'little'))
    for i in range(0,len(data),8):out.append(0);out.extend(data[i:i+8])
    return bytes(out)

def finish_crc(data,skip=12):
    data=bytearray(data);struct.pack_into('>I',data,4,len(data))
    struct.pack_into('>I',data,8,zlib.crc32(data[skip:])&0xffffffff)
    return bytes(data)

