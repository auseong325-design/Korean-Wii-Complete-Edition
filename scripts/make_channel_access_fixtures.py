def source_array(text,name):
    match=re.search(r'\b'+re.escape(name)+r'\s*=\s*\[\]byte\{([^}]+)\}',text)
    if not match:raise ValueError('Public protocol constant not found')
    return bytes(int(v.strip(),0)for v in match[1].split(',')if v.strip())

