def go_header(path,values,struct_name='Header',aliases=None):
    text=path.read_text()
    for before,after in(aliases or {}).items():text=text.replace(before,after)
    body=re.search(r'type '+re.escape(struct_name)+r' struct \{(.*?)\n\}',text,re.S)[1]
    out=bytearray()
    sizes={'uint8':1,'byte':1,'uint16':2,'uint32':4,'uint64':8}
    for name,count,kind in re.findall(r'^\s*(\w+)\s+(?:\[(\d+)\])?(uint8|uint16|uint32|uint64|byte)\s*$',body,re.M):
        size=sizes[kind];count=int(count or 1);value=values.get(name,0)
        if isinstance(value,bytes):
            if len(value)>size*count:raise ValueError('Header field capacity')
            out.extend(value.ljust(size*count,b'\0'))
        else:out.extend(int(value).to_bytes(size,'big')*count)
    return bytes(out)

