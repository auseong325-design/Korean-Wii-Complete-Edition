def _eol(text,new):
    return new.replace('\n','\r\n')if '\r\n'in text else new

def _patch(path,old,new):
    text=path.read_bytes().decode('utf-8',errors='surrogateescape')
    o,n=_eol(text,old),_eol(text,new)
    if text.count(o)!=1:raise ValueError(f'Patch anchor not unique in {path.name}: {old[:60]!r}')
    path.write_bytes(text.replace(o,n).encode('utf-8',errors='surrogateescape'))

def _region(path,start,end,new):
    text=path.read_bytes().decode('utf-8',errors='surrogateescape');s=_eol(text,start)
    if text.count(s)!=1:raise ValueError(f'Region start not unique in {path.name}')
    a=text.index(s)
    if end is None:b=len(text)
    else:
        e=_eol(text,end)
        if text.count(e)!=1 or text.index(e)<a:raise ValueError(f'Region end not unique in {path.name}')
        b=text.index(e)
    path.write_bytes((text[:a]+_eol(text,new)+text[b:]).encode('utf-8',errors='surrogateescape'))

def _escape(text):return text.replace('\\','\\\\').replace('"','\\"')

def ko_catalog(config=None):
    """gettext catalog in the format LoadLanguage reads (LF, every line < 200 bytes)."""
    config=config or json.loads(CONFIG.read_text(encoding='utf-8'))
    rows=dict(config['messages']);rows.update(config['kwce_messages'])
    lines=['# KWCE Korean catalog for WiiLink Set Personal Data','# generated from configs/personal-data-messages-v1-ko.json','']
    for msgid in sorted(rows):lines+=[f'msgid "{_escape(msgid)}"',f'msgstr "{_escape(rows[msgid])}"','']
    data=('\n'.join(lines)+'\n').encode('utf-8')
    if any(len(line)>=200 for line in data.split(b'\n')):raise ValueError('Catalog line exceeds LoadLanguage buffer')
    return data,len(rows)

def hash_string(text):
    """Python port of gettext.cpp hash_string (hashpjw over UTF-8 bytes)."""
    value=0
    for byte in text.encode('utf-8'):
        value=((value<<4)+byte)&0xffffffff;high=value&0xf0000000
        if high:value^=high>>24;value^=high
    return value

