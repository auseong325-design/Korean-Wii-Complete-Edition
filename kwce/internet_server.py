"""Internet Channel local page server, revision 2 (C# source for the capability-0 helper).

Why a new server: Dolphin forwards host poll() events to the Wii unchanged
(external/other-tools/dolphin-reference/Socket.cpp, UpdatePollCommands /
ConvertEvents). On Windows, WSAPoll reports POLLHUP as soon as the peer's FIN
has arrived, even while response bytes are still unread. The revision-1 server
(scripts/ChannelTestServer.cs) half-closes immediately after every response, so
the Internet Channel's first poll sees POLLIN|POLLHUP, drops the connection
without reading, and retries: five identical GETs within ~80 ms and a blank
page (also seen for /update/wii 404s). NHTTP/KD channels were unaffected.

Revision 2 keeps connections persistent (HTTP/1.1 keep-alive), never shuts
down its send side right after a response, waits for the client to close
first, and closes an idle connection only when nothing is unread (FIN, not RST).
Responses are written in one send with TCP_NODELAY. It logs the request line
and header NAMES only (never values, query strings or bodies), serves GET/HEAD
from local-feed (routes.tsv: key, file, content type) and answers anything
else with 405 without reading it.
"""
import os
import subprocess
from pathlib import Path

NOT_FOUND_TEXT = ('<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 4.01//EN">\n<html lang="ko"><head>'
                  '<meta http-equiv="Content-Type" content="text/html; charset=utf-8">'
                  "<style type=\"text/css\">body{font-family:'Wii NTLG PGothic Regular',sans-serif;}</style>"
                  '<title>404</title></head><body><h1>404</h1>'
                  '<p>KWCE 시험 서버에 이 주소의 페이지가 없습니다. (시험용 응답)</p>'
                  '<p><a href="/">KWCE 시험 색인</a></p></body></html>\n')


def _csharp_literal(text):
    out = []
    for ch in text:
        if ch == '\\':
            out.append('\\\\')
        elif ch == '"':
            out.append('\\"')
        elif ch == '\n':
            out.append('\\n')
        elif ord(ch) < 0x20 or ord(ch) > 0x7e:
            out.append('\\u%04X' % ord(ch))
        else:
            out.append(ch)
    return '"' + ''.join(out) + '"'


SERVER_TEMPLATE = r'''// KWCE Internet Channel local page server, revision 2 (generated by kwce/internet_server.py).
// Same zero-capability AppContainer as Dolphin; listens on 127.0.0.2:80 only.
// Persistent HTTP/1.1; never half-closes right after a response (Windows WSAPoll would
// report POLLHUP to the Wii through Dolphin before the response is read).
// Logs request lines and header NAMES only; values, queries and bodies are never stored.
using System;
using System.Collections.Generic;
using System.Diagnostics;
using System.IO;
using System.Net;
using System.Net.Sockets;
using System.Text;
using System.Text.RegularExpressions;
using System.Threading;

class InternetServer {
 static string root, feed, log;
 static readonly Dictionary<string,string> routes = new Dictionary<string,string>();
 static readonly Dictionary<string,string> types = new Dictionary<string,string>();
 static readonly object mutex = new object();
 static int connections = 0;
 const int FirstRequestMs = 10000;
 const int IdleMs = 15000;
 const int HeaderByteMs = 5000;
 const int CloseWaitMs = 5000;
 const int MaxHead = 16384;
 static readonly byte[] NotFoundBody = Encoding.UTF8.GetBytes(@@NOT_FOUND@@);

 static void Log(string line) {
  lock (mutex) File.AppendAllText(log, DateTime.UtcNow.ToString("o") + "\t" + line + "\n");
 }

 static string Safe(string text) {
  string s = Regex.Replace(text, "[0-9]{6,}", "ID");
  return Regex.Replace(s, "[^A-Za-z0-9/_\\.\\-]", "_");
 }

 static string Reason(SocketException e) {
  if (e.SocketErrorCode == SocketError.ConnectionReset) return "client-reset";
  if (e.SocketErrorCode == SocketError.ConnectionAborted) return "aborted";
  if (e.SocketErrorCode == SocketError.TimedOut) return "timeout";
  return "socket-" + e.SocketErrorCode;
 }

 // -2 timeout, -1 end of stream, otherwise one byte.
 static int ReadByte(Socket sock, int ms) {
  if (!sock.Poll(ms * 1000, SelectMode.SelectRead)) return -2;
  byte[] one = new byte[1];
  int n = sock.Receive(one, 0, 1, SocketFlags.None);
  return n == 0 ? -1 : one[0];
 }

 static byte[] ReadHead(Socket sock, int firstByteMs, out string end) {
  MemoryStream head = new MemoryStream(); uint last = 0; end = null;
  while (true) {
   int b = ReadByte(sock, head.Length == 0 ? firstByteMs : HeaderByteMs);
   if (b == -2) { end = head.Length == 0 ? "idle-timeout" : "timeout-in-head"; return null; }
   if (b == -1) { end = head.Length == 0 ? "client-close" : "eof-in-head"; return null; }
   head.WriteByte((byte)b);
   last = (last << 8) | (byte)b;
   if (last == 0x0d0a0d0a) return head.ToArray();
   if (head.Length > MaxHead) { end = "head-too-long"; return null; }
  }
 }

 static void Send(Socket sock, byte[] data) {
  int sent = 0;
  while (sent < data.Length) {
   int n = sock.Send(data, sent, data.Length - sent, SocketFlags.None);
   if (n <= 0) throw new SocketException((int)SocketError.ConnectionAborted);
   sent += n;
  }
 }

 static bool Discard(Socket sock, long length) {
  byte[] buffer = new byte[4096];
  while (length > 0) {
   if (!sock.Poll(HeaderByteMs * 1000, SelectMode.SelectRead)) return false;
   int n = sock.Receive(buffer, 0, (int)Math.Min(length, buffer.Length), SocketFlags.None);
   if (n <= 0) return false;
   length -= n;
  }
  Array.Clear(buffer, 0, buffer.Length);
  return true;
 }

 // The client asked to close: let it close first, so its FIN precedes ours.
 static string WaitClientClose(Socket sock) {
  byte[] buffer = new byte[4096]; long extra = 0; Stopwatch wait = Stopwatch.StartNew();
  while (wait.ElapsedMilliseconds < CloseWaitMs && extra <= 1048576) {
   int left = (int)(CloseWaitMs - wait.ElapsedMilliseconds);
   if (left <= 0 || !sock.Poll(left * 1000, SelectMode.SelectRead)) break;
   int n = sock.Receive(buffer);
   if (n == 0) return extra > 0 ? "client-close-after-extra-bytes" : "client-close";
   extra += n;
  }
  try { sock.Shutdown(SocketShutdown.Send); } catch (SocketException) {}
  Stopwatch drain = Stopwatch.StartNew();
  try {
   while (drain.ElapsedMilliseconds < 500 && sock.Poll(100000, SelectMode.SelectRead)) { if (sock.Receive(buffer) == 0) break; }
  } catch (SocketException) {}
  return "server-close-after-wait";
 }

 static void Handle(TcpClient client) {
  int id = Interlocked.Increment(ref connections); Stopwatch clock = Stopwatch.StartNew();
  int served = 0; string end = "unknown";
  using (client) {
   Socket sock = client.Client; sock.NoDelay = true; sock.SendTimeout = 10000;
   try {
    while (true) {
     byte[] head = ReadHead(sock, served == 0 ? FirstRequestMs : IdleMs, out end);
     if (head == null) break;
     string[] lines = Encoding.ASCII.GetString(head).Split(new string[] { "\r\n" }, StringSplitOptions.None);
     string[] req = lines[0].Split(' ');
     if (req.Length != 3) { end = "bad-request-line"; break; }
     string method = req[0], version = req[2], path = req[1];
     int query = path.IndexOf('?'); if (query >= 0) path = path.Substring(0, query);
     if (path.Contains("://")) { Uri u; if (!Uri.TryCreate(path, UriKind.Absolute, out u)) { end = "bad-uri"; break; } path = u.AbsolutePath; }
     List<string> names = new List<string>(); bool close = false, keepAlive = false, chunked = false; long length = 0;
     for (int i = 1; i < lines.Length; i++) {
      int colon = lines[i].IndexOf(':'); if (colon <= 0) continue;
      string name = lines[i].Substring(0, colon).Trim(), value = lines[i].Substring(colon + 1).Trim().ToLowerInvariant();
      names.Add(Regex.Replace(name, "[^A-Za-z0-9\\-]", "_"));
      switch (name.ToLowerInvariant()) {
       case "connection": if (value.Contains("close")) close = true; if (value.Contains("keep-alive")) keepAlive = true; break;
       case "content-length": if (!long.TryParse(value, out length)) length = -1; break;
       case "transfer-encoding": if (value.Contains("chunked")) chunked = true; break;
      }
     }
     Log("request\tconn=" + id + "\tn=" + (served + 1) + "\t" + Safe(method) + "\t" + Safe(path) + "\t" + Safe(version) + "\theaders=" + string.Join(",", names.ToArray()));
     bool get = method == "GET", headOnly = method == "HEAD";
     bool keep = !close && (version == "HTTP/1.1" || keepAlive);
     int status; byte[] data; string type;
     if (!get && !headOnly) { status = 405; data = new byte[0]; type = "text/plain"; keep = false; }
     else {
      if (chunked || length < 0 || length > 1048576 || !Discard(sock, length)) { end = "unsupported-request-body"; break; }
      string mapped; string key = method + " " + path; bool found = routes.TryGetValue(key, out mapped);
      if (!found) { key = "* " + path; found = routes.TryGetValue(key, out mapped); }
      string file = found ? Path.GetFullPath(Path.Combine(feed, mapped)) : null;
      if (file != null && !file.StartsWith(feed + Path.DirectorySeparatorChar, StringComparison.OrdinalIgnoreCase)) file = null;
      if (file != null && File.Exists(file)) { status = 200; data = File.ReadAllBytes(file); type = types[key]; }
      else { status = 404; data = NotFoundBody; type = "text/html; charset=utf-8"; }
     }
     StringBuilder h = new StringBuilder();
     h.Append("HTTP/1.1 ").Append(status).Append(status == 200 ? " OK" : status == 404 ? " Not Found" : " Method Not Allowed").Append("\r\n");
     h.Append("Content-Type: ").Append(type).Append("\r\n");
     h.Append("Content-Length: ").Append(data.Length).Append("\r\n");
     h.Append("Cache-Control: no-store\r\n");
     if (status == 405) h.Append("Allow: GET, HEAD\r\n");
     h.Append(keep ? "Connection: keep-alive\r\nKeep-Alive: timeout=15\r\n" : "Connection: close\r\n");
     h.Append("\r\n");
     byte[] header = Encoding.ASCII.GetBytes(h.ToString());
     byte[] packet = new byte[header.Length + (headOnly ? 0 : data.Length)];
     Buffer.BlockCopy(header, 0, packet, 0, header.Length);
     if (!headOnly) Buffer.BlockCopy(data, 0, packet, header.Length, data.Length);
     Send(sock, packet);
     served++;
     Log("response\tconn=" + id + "\tn=" + served + "\t" + status + "\t" + data.Length + "\t" + (keep ? "keep-alive" : "close"));
     if (!keep) { end = status == 405 ? "closed-after-405" : WaitClientClose(sock); break; }
    }
   } catch (SocketException e) { end = Reason(e); }
   catch (ObjectDisposedException) { end = "disposed"; }
  }
  Log("conn-end\tconn=" + id + "\trequests=" + served + "\tend=" + end + "\tms=" + clock.ElapsedMilliseconds);
 }

 static int Main(string[] args) {
  try {
   root = Path.GetFullPath(args[0]); feed = Path.Combine(root, "local-feed"); log = Path.Combine(root, "access-http.tsv");
   foreach (string line in File.ReadAllLines(Path.Combine(feed, "routes.tsv"))) {
    if (line.Length == 0 || line.StartsWith("#")) continue;
    string[] r = line.Split('\t');
    if (r.Length != 3) throw new Exception("Route format");
    routes.Add(r[0], r[1]); types.Add(r[0], r[2]);
   }
   TcpListener listener = new TcpListener(IPAddress.Parse("127.0.0.2"), 80); listener.Start();
   Log("server-start\trevision=2\troutes=" + routes.Count + "\tmode=persistent");
   File.WriteAllText(Path.Combine(root, "feed-ready.txt"), "listening");
   while (true) {
    TcpClient c = listener.AcceptTcpClient();
    Thread t = new Thread(() => { try { Handle(c); } catch (Exception e) { Log("request-failed\t" + e.GetType().Name); } });
    t.IsBackground = true; t.Start();
   }
  } catch (Exception e) {
   try { File.WriteAllText(Path.Combine(root, "feed-server-error.txt"), e.GetType().Name + ": " + e.Message); } catch {}
   return 3;
  }
 }
}
'''


def server_source():
    source = SERVER_TEMPLATE.replace('@@NOT_FOUND@@', _csharp_literal(NOT_FOUND_TEXT))
    if any(ord(c) > 0x7e for c in source):
        raise ValueError('Server source must stay ASCII (csc reads BOM-less files with the ANSI code page)')
    return source


def compile_csharp(source_file, exe_file):
    compiler = Path(os.environ['WINDIR']) / 'Microsoft.NET/Framework64/v4.0.30319/csc.exe'
    result = subprocess.run([str(compiler), '/nologo', '/target:exe', '/platform:x64', '/out:' + str(exe_file), str(source_file)],
                            capture_output=True, text=True)
    if result.returncode:
        raise ValueError('C# compile failed: ' + (result.stdout + result.stderr)[-1500:])
